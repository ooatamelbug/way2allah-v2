// B7a browser-download lab: fixture servers (disposable, local only; never deployed).
//
//   :8000  page origin   GET /page.html          the test page (prototype save module + play button)
//                        GET /route?to=<url>     302 to <url>, like var-download / recite-download today
//   :8001  media, CORS   GET|HEAD /f/<name>      Access-Control-Allow-Origin: *
//   :8002  media, none   GET|HEAD /f/<name>      no CORS headers
//
// Query options on /f/<name>: rate=<bytes/s> throttles; cut=<bytes> destroys the socket after that many bytes
// (an interrupted transfer whose Content-Length promised more).
//
// Files: small.mp3 / small.mp4 are real media generated by ffmpeg (see run.sh). big50.* and big400.* are
// deterministic pseudo-random streams (50 MiB / 400 MiB) generated on the fly, so nothing large is stored.
import http from 'node:http';
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';

const MEDIA_DIR = process.env.MEDIA_DIR || '/work/media';
const MiB = 1024 * 1024;
const TYPES = { mp3: 'audio/mpeg', mp4: 'video/mp4' };

// One 1 MiB seeded block; block i is the base block with i written into its first 8 bytes, so a duplicated,
// dropped or reordered block changes the hash.
const BASE = crypto.createHash('sha512').update('w2a-b7a-seed').digest();
const BLOCK = Buffer.alloc(MiB);
for (let o = 0; o < MiB; o += BASE.length) BASE.copy(BLOCK, o);
function block(i) {
    const b = Buffer.from(BLOCK);
    b.writeBigUInt64BE(BigInt(i), 0);
    return b;
}

const generated = { big50: 50 * MiB, big400: 400 * MiB };
const manifest = {};

function describe(name) {
    const [stem, ext] = name.split('.');
    if (!TYPES[ext]) return null;
    if (generated[stem]) return { name, size: generated[stem], type: TYPES[ext], generated: true };
    const file = path.join(MEDIA_DIR, name);
    if (!fs.existsSync(file)) return null;
    return { name, size: fs.statSync(file).size, type: TYPES[ext], file };
}

function sha256Of(d) {
    const h = crypto.createHash('sha256');
    if (d.generated) {
        for (let i = 0; i < d.size / MiB; i++) h.update(block(i));
    } else {
        h.update(fs.readFileSync(d.file));
    }
    return h.digest('hex');
}

for (const name of ['small.mp3', 'small.mp4', 'big50.mp3', 'big50.mp4', 'big400.mp3', 'big400.mp4']) {
    const d = describe(name);
    if (d) manifest[name] = { size: d.size, type: d.type, sha256: sha256Of(d) };
}
fs.writeFileSync('/work/manifest.json', JSON.stringify(manifest, null, 2));

function serveFile(req, res, cors) {
    const url = new URL(req.url, 'http://x');
    const name = decodeURIComponent(url.pathname.replace(/^\/f\//, ''));
    const d = describe(name);
    const headers = {};
    if (cors) {
        headers['Access-Control-Allow-Origin'] = '*';
    }
    if (!d) {
        res.writeHead(404, headers);
        return res.end();
    }
    // Like archive.org today: an inline media type, Content-Length, ranges advertised, and no Content-Disposition.
    Object.assign(headers, { 'Content-Type': d.type, 'Content-Length': String(d.size), 'Accept-Ranges': 'bytes', 'Cache-Control': 'no-store' });
    res.writeHead(200, headers);
    if (req.method === 'HEAD') return res.end();

    const rate = Number(url.searchParams.get('rate') || 0);
    const cut = Number(url.searchParams.get('cut') || 0);
    const total = d.size;
    const chunk = 256 * 1024;
    const fileData = d.generated ? null : fs.readFileSync(d.file);
    let sent = 0;
    let closed = false;
    req.on('close', () => { closed = true; });

    const piece = (offset, len) => {
        if (fileData) return fileData.subarray(offset, offset + len);
        const out = Buffer.alloc(len);
        let filled = 0;
        while (filled < len) {
            const pos = offset + filled;
            const b = block(Math.floor(pos / MiB));
            const inBlock = pos % MiB;
            const n = Math.min(len - filled, MiB - inBlock);
            b.copy(out, filled, inBlock, inBlock + n);
            filled += n;
        }
        return out;
    };

    const pump = () => {
        while (!closed && sent < total) {
            if (cut && sent >= cut) {
                req.socket.destroy();
                return;
            }
            const len = Math.min(chunk, total - sent, cut ? cut - sent : Infinity);
            const ok = res.write(piece(sent, len));
            sent += len;
            if (rate) {
                setTimeout(pump, (len / rate) * 1000);
                return;
            }
            if (!ok) {
                res.once('drain', pump);
                return;
            }
        }
        if (!closed && sent >= total) res.end();
    };
    pump();
}

const PAGE = fs.readFileSync(new URL('./page.html', import.meta.url));

http.createServer((req, res) => {
    const url = new URL(req.url, 'http://x');
    if (url.pathname === '/page.html') {
        res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'no-store' });
        return res.end(PAGE);
    }
    if (url.pathname === '/route') {
        res.writeHead(302, { Location: url.searchParams.get('to') || '/' });
        return res.end();
    }
    res.writeHead(404);
    res.end();
}).listen(8000);
http.createServer((req, res) => serveFile(req, res, true)).listen(8001);
http.createServer((req, res) => serveFile(req, res, false)).listen(8002);
console.log('ready');
