<?php

namespace App\Console\Commands;

use FilesystemIterator;
use Illuminate\Console\Command;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use SplFileInfo;
use Symfony\Component\Console\Exception\ExceptionInterface as ConsoleInputException;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Output\OutputInterface;
use ZipArchive;

/**
 * Read-only guard for the owner-controlled manual cPanel packaging procedure (P0 split layout, owner-approved
 * 2026-11-09). Run it on a staged package directory or the finished ZIP before uploading; it inspects entry
 * names, types and (for the front controller only) bytes, and never extracts, writes or modifies anything.
 *
 * Every entry is validated BEFORE any protected-path rule (owner-approved correction D1 / D2 / D4, 2026-11-09):
 *  - `unsafe_entry_name` — a leading separator / absolute path, a backslash, a NUL byte, an empty segment (repeated
 *    separators), a `.` or `..` segment, or a top level other than the `newapp/` and `laravel-app/` directories.
 *    Unsafe names are rejected, never normalised and accepted. A single trailing slash is allowed only on a genuine
 *    directory entry; directory markers are subject to the same protected-path rules as files.
 *  - `duplicate_entry` — the same name twice (ZIP entries are inspected and read by index, never by name).
 *  - `symlink_entry` — a ZIP entry whose Unix file-type bits mark a symbolic link, or any symbolic link in a staged
 *    directory (reported, never followed, never read through).
 *  ZIP names are read from the archive's central directory as raw bytes and cross-checked with libzip, which
 *  silently rewrites some names (a NUL byte becomes a space; an extractor treating names as C strings would
 *  truncate there instead) — any difference is `unsafe_entry_name`. ZIP64 archives and archives with prepended
 *  data are reported as unreadable rather than partially checked. In a ZIP, a trailing slash marks a directory only
 *  when the Unix mode bits do not say "regular file".
 *
 * Protected paths (applied to every safe entry):
 *  1. `newapp/index.php` must be a file byte-identical to `deploy/split-layout/newapp-index.php` (the local
 *     `public/index.php` is the co-located variant) — `front_controller_not_split`; with `--full` it must be present
 *     (`front_controller_missing`);
 *  2. nothing inside `newapp/w2a_autocomplete/` (runtime lists regenerated by the AdminCP) — `runtime_autocomplete_file`;
 *  3. nothing inside `laravel-app/bootstrap/cache/` except its `.gitignore` — `bootstrap_cache_artifact`;
 *  4. nothing at or under `laravel-app/public/` (not served in the split layout) — `application_public_file`.
 *
 * Modes: incremental (default) — the front controller may be absent; `--full` — a complete release, which must
 * contain the canonical front controller.
 *
 * Exit codes: 0 = package passes; 1 = violations; 2 = package could not be read; 64 = usage error.
 */
class VerifyDeploymentPackage extends Command
{
    public const EXIT_CLEAN = 0;

    public const EXIT_VIOLATIONS = 1;

    public const EXIT_UNREADABLE = 2;

    public const EXIT_USAGE = 64;

    public const TEMPLATE = 'deploy/split-layout/newapp-index.php';

    private const FRONT_CONTROLLER = 'newapp/index.php';

    private const TOP_LEVEL = ['newapp', 'laravel-app'];

    private const UNIX_FILE_TYPE_MASK = 0170000;

    private const UNIX_SYMLINK = 0120000;

    private const UNIX_REGULAR_FILE = 0100000;

    private const UNIX_DIRECTORY = 0040000;

    protected $signature = 'deploy:verify-package
        {package : A staged package directory or a .zip file}
        {--full : The package is a complete release: newapp/index.php must be present}
        {--json : Machine-readable JSON output}';

    protected $description = 'Read-only check of a split-layout deployment package (entry names, front controller, runtime files, bootstrap cache)';

    public function run(InputInterface $input, OutputInterface $output): int
    {
        try {
            return parent::run($input, $output);
        } catch (ConsoleInputException $e) {
            $output->writeln('<error>'.$e->getMessage().'</error>');

            return self::EXIT_USAGE;
        }
    }

    public function handle(): int
    {
        $package = (string) $this->argument('package');
        $full = (bool) $this->option('full');
        $template = @file_get_contents(base_path(self::TEMPLATE));

        $entries = $template === false ? null : $this->entries($package);
        if ($entries === null) {
            return $this->report($package, $full, self::EXIT_UNREADABLE, [], $template === false
                ? 'The canonical front controller template ('.self::TEMPLATE.') is missing.'
                : 'The package could not be read (expected an existing directory or a readable .zip file).');
        }

        $violations = [];
        $seen = [];
        $frontControllers = [];
        $frontControllerSymlinked = false;

        foreach ($entries as $entry) {
            $raw = $entry['name'];
            $path = $this->safePath($raw, $entry['directory']);

            if ($path === null) {
                $violations[] = $this->violation('unsafe_entry_name', $raw, 'Unsafe entry name: absolute or leading separator, backslash, NUL, empty / "." / ".." segment, or a top level other than newapp/ and laravel-app/.');

                continue;
            }

            if (isset($seen[$path])) {
                $violations[] = $this->violation('duplicate_entry', $raw, 'The same path appears more than once; the extracted result would depend on entry order.');
            }
            $seen[$path] = true;

            if ($entry['symlink']) {
                $violations[] = $this->violation('symlink_entry', $raw, 'Symbolic links are not allowed in a package (they are not followed or read).');
                $frontControllerSymlinked = $frontControllerSymlinked || $path === self::FRONT_CONTROLLER;

                continue;
            }

            foreach ($this->protectedPathViolations($path, $entry['directory']) as $violation) {
                $violations[] = $violation;
            }

            if ($path === self::FRONT_CONTROLLER) {
                $frontControllers[] = $entry;
            }
        }

        // Exactly one regular-file front controller is compared; duplicates are already violations above.
        if (count($frontControllers) === 1 && ! $frontControllers[0]['directory']) {
            $contents = ($frontControllers[0]['read'])();
            if ($contents !== $template) {
                $local = @file_get_contents(public_path('index.php'));
                $violations[] = $this->violation('front_controller_not_split', self::FRONT_CONTROLLER, $local !== false && $contents === $local
                    ? 'This is the local co-located public/index.php; ship '.self::TEMPLATE.' instead.'
                    : 'The front controller differs from '.self::TEMPLATE.'.');
            }
        }

        if ($full && $frontControllers === [] && ! $frontControllerSymlinked) {
            $violations[] = $this->violation('front_controller_missing', self::FRONT_CONTROLLER, 'A full release must contain '.self::FRONT_CONTROLLER.' (a copy of '.self::TEMPLATE.').');
        }

        return $this->report($package, $full, $violations === [] ? self::EXIT_CLEAN : self::EXIT_VIOLATIONS, $violations, null);
    }

    /**
     * The validated path (without a directory's single trailing slash), or null when the name is unsafe.
     */
    private function safePath(string $name, bool $directory): ?string
    {
        if ($name === '' || str_contains($name, "\0") || str_contains($name, '\\') || str_starts_with($name, '/')) {
            return null;
        }

        if (str_ends_with($name, '/')) {
            if (! $directory) {
                return null;
            }
            $name = substr($name, 0, -1);
        }

        $segments = explode('/', $name);
        foreach ($segments as $segment) {
            if ($segment === '' || $segment === '.' || $segment === '..') {
                return null;
            }
        }

        if (! in_array($segments[0], self::TOP_LEVEL, true) || (count($segments) === 1 && ! $directory)) {
            return null;
        }

        return $name;
    }

    /** @return list<array{rule: string, entry: string, message: string}> */
    private function protectedPathViolations(string $path, bool $directory): array
    {
        $inside = fn (string $root) => str_starts_with($path, $root.'/');
        $atOrInside = fn (string $root) => $path === $root || $inside($root);
        $violations = [];

        if (($path === self::FRONT_CONTROLLER && $directory) || $inside(self::FRONT_CONTROLLER)) {
            $violations[] = $this->violation('front_controller_not_split', $path, self::FRONT_CONTROLLER.' must be a file.');
        }
        // A directory marker for the protected directory itself is harmless (it already exists on the server);
        // anything inside it — file or directory — and a file replacing it are refused.
        if ($directory ? $inside('newapp/w2a_autocomplete') : $atOrInside('newapp/w2a_autocomplete')) {
            $violations[] = $this->violation('runtime_autocomplete_file', $path, 'Autocomplete lists are regenerated on the server by the AdminCP; shipping them overwrites live data.');
        }
        if (($directory ? $inside('laravel-app/bootstrap/cache') : $atOrInside('laravel-app/bootstrap/cache'))
            && $path !== 'laravel-app/bootstrap/cache/.gitignore') {
            $violations[] = $this->violation('bootstrap_cache_artifact', $path, 'Bootstrap cache files are environment-specific; the server regenerates them.');
        }
        if ($atOrInside('laravel-app/public')) {
            $violations[] = $this->violation('application_public_file', $path, 'Public files belong in newapp/; laravel-app/public/ is not served in the split layout.');
        }

        return $violations;
    }

    /**
     * Every entry, in package order (duplicates preserved).
     *
     * @return list<array{name: string, directory: bool, symlink: bool, read: callable(): (string|false)}>|null
     */
    private function entries(string $package): ?array
    {
        if (is_link($package)) {
            return null;
        }

        if (is_dir($package)) {
            $root = rtrim((string) realpath($package), '/');
            $entries = [];
            // SELF_FIRST lists directories too; without FOLLOW_SYMLINKS a symlinked directory is reported as one
            // symlink entry (never descended into), so it cannot silently disappear from the check.
            $iterator = new RecursiveIteratorIterator(
                new RecursiveDirectoryIterator($root, FilesystemIterator::SKIP_DOTS),
                RecursiveIteratorIterator::SELF_FIRST,
            );
            /** @var SplFileInfo $file */
            foreach ($iterator as $file) {
                $path = $file->getPathname();
                $name = substr($path, strlen($root) + 1);
                $symlink = $file->isLink();
                $directory = ! $symlink && $file->isDir();
                $entries[] = [
                    'name' => $directory ? $name.'/' : $name,
                    'directory' => $directory,
                    'symlink' => $symlink,
                    'read' => $symlink || $directory ? fn () => false : fn () => @file_get_contents($path),
                ];
            }

            return $entries;
        }

        if (! is_file($package) || ! class_exists(ZipArchive::class)) {
            return null;
        }

        $rawNames = $this->rawCentralDirectoryNames($package);
        $zip = new ZipArchive;
        if ($rawNames === null || $zip->open($package, ZipArchive::RDONLY) !== true || $zip->numFiles !== count($rawNames)) {
            return null;
        }

        $entries = [];
        for ($i = 0; $i < $zip->numFiles; $i++) {
            $name = $zip->getNameIndex($i, ZipArchive::FL_UNCHANGED | ZipArchive::FL_ENC_RAW);
            if ($name === false) {
                return null;
            }
            // libzip's view differs from the stored bytes (e.g. NUL → space): validate the stored bytes, which then
            // fail; an altered name is never accepted.
            if ($name !== $rawNames[$i]) {
                $name = str_contains($rawNames[$i], "\0") ? $rawNames[$i] : "\0".$rawNames[$i];
            }

            $opsys = 0;
            $attributes = 0;
            $type = $zip->getExternalAttributesIndex($i, $opsys, $attributes, ZipArchive::FL_UNCHANGED) && $opsys === ZipArchive::OPSYS_UNIX
                ? (($attributes >> 16) & self::UNIX_FILE_TYPE_MASK)
                : 0;
            $symlink = $type === self::UNIX_SYMLINK;
            $directory = ! $symlink && ($type === self::UNIX_DIRECTORY || (str_ends_with($name, '/') && $type !== self::UNIX_REGULAR_FILE));
            $index = $i;

            $entries[] = [
                'name' => $name,
                'directory' => $directory,
                'symlink' => $symlink,
                'read' => $symlink || $directory ? fn () => false : fn () => $zip->getFromIndex($index, 0, ZipArchive::FL_UNCHANGED),
            ];
        }

        return $entries;
    }

    /**
     * Entry names exactly as stored in the ZIP central directory, in index order — or null for an archive this
     * check does not fully understand (no end-of-central-directory record, ZIP64, prepended data, truncation).
     *
     * @return list<string>|null
     */
    private function rawCentralDirectoryNames(string $path): ?array
    {
        $size = @filesize($path);
        $handle = @fopen($path, 'rb');
        if ($handle === false || $size === false || $size < 22) {
            return null;
        }

        try {
            $tailLength = min($size, 22 + 0xFFFF);
            fseek($handle, $size - $tailLength);
            $tail = (string) fread($handle, $tailLength);
            $at = strrpos($tail, "PK\x05\x06");
            if ($at === false || strlen($tail) < $at + 22) {
                return null;
            }

            /** @var array{entries: int, size: int, offset: int} $end */
            $end = unpack('ventries/Vsize/Voffset', substr($tail, $at + 10, 10));
            if ($end['entries'] === 0xFFFF || $end['size'] === 0xFFFFFFFF || $end['offset'] === 0xFFFFFFFF
                || $size - $tailLength + $at !== $end['offset'] + $end['size']) {
                return null;
            }

            $directory = '';
            if ($end['size'] > 0) {
                fseek($handle, $end['offset']);
                $directory = (string) fread($handle, $end['size']);
            }
            if (strlen($directory) !== $end['size']) {
                return null;
            }

            $names = [];
            for ($i = 0, $at = 0; $i < $end['entries']; $i++) {
                if (substr($directory, $at, 4) !== "PK\x01\x02" || strlen($directory) < $at + 46) {
                    return null;
                }
                /** @var array{name: int, extra: int, comment: int} $lengths */
                $lengths = unpack('vname/vextra/vcomment', substr($directory, $at + 28, 6));
                $names[] = substr($directory, $at + 46, $lengths['name']);
                $at += 46 + $lengths['name'] + $lengths['extra'] + $lengths['comment'];
            }

            return $at === strlen($directory) ? $names : null;
        } finally {
            fclose($handle);
        }
    }

    /** @return array{rule: string, entry: string, message: string} */
    private function violation(string $rule, string $entry, string $message): array
    {
        return ['rule' => $rule, 'entry' => $this->printable($entry), 'message' => $message];
    }

    /** Control characters (e.g. NUL) are shown escaped so a hostile name cannot corrupt the output. */
    private function printable(string $name): string
    {
        return (string) preg_replace_callback('/[\x00-\x1F\x7F]/', fn ($m) => sprintf('\\x%02X', ord($m[0])), $name);
    }

    /** @param list<array{rule: string, entry: string, message: string}> $violations */
    private function report(string $package, bool $full, int $exit, array $violations, ?string $error): int
    {
        if ($this->option('json')) {
            $this->line((string) json_encode([
                'status' => [self::EXIT_CLEAN => 'clean', self::EXIT_VIOLATIONS => 'violations', self::EXIT_UNREADABLE => 'unreadable'][$exit],
                'exit_code' => $exit,
                'mode' => $full ? 'full' : 'incremental',
                'package' => basename($package),
                'violations' => $violations,
                'error' => $error,
                'note' => 'Read-only: the package was inspected, not extracted or modified.',
            ], JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_INVALID_UTF8_SUBSTITUTE));

            return $exit;
        }

        $this->line('Deployment package check (read-only, '.($full ? 'full' : 'incremental').' mode): '.basename($package));
        if ($error !== null) {
            $this->error($error);
        } elseif ($violations === []) {
            $this->info('No violations.');
        } else {
            $this->table(['rule', 'entry', 'message'], array_map(fn ($v) => [$v['rule'], $v['entry'], $v['message']], $violations));
        }
        $this->line('Exit code: '.$exit);

        return $exit;
    }
}
